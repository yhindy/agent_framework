/**
 * Creates a default MinionsConfig with minimal required fields.
 *
 * @param name - Project name
 * @param defaultBaseBranch - Default base branch (e.g., 'main', 'develop')
 * @returns A valid MinionsConfig with sensible defaults
 *
 * @example
 * ```typescript
 * const config = createDefaultMinionsConfig('my-app', 'main')
 * // Returns:
 * // {
 * //   version: '2.0',
 * //   project: { name: 'my-app', defaultBaseBranch: 'main' },
 * //   setup: { filesToCopy: [], postSetupCommands: [] }
 * // }
 * ```
 */
export function createDefaultMinionsConfig(
  name: string,
  defaultBaseBranch?: string
): MinionsConfig {
  const project: MinionsConfigProject = { name }
  if (defaultBaseBranch !== undefined) {
    project.defaultBaseBranch = defaultBaseBranch
  }
  return {
    version: '2.0',
    project,
    setup: {
      filesToCopy: [],
      postSetupCommands: []
    }
  }
}

/**
 * Type guard to validate if an unknown value is a valid MinionsConfig.
 *
 * Performs runtime validation to ensure the object has all required fields
 * and correct structure. Useful for validating parsed JSON.
 *
 * @param value - Unknown value to validate
 * @returns True if value is a valid MinionsConfig
 *
 * @example
 * ```typescript
 * const parsed = JSON.parse(fileContents)
 * if (isValidMinionsConfig(parsed)) {
 *   // parsed is now typed as MinionsConfig
 *   console.log(parsed.project.name)
 * }
 * ```
 */
export function isValidMinionsConfig(value: unknown): value is MinionsConfig {
  if (value === null || value === undefined) {
    return false
  }

  if (typeof value !== 'object' || Array.isArray(value)) {
    return false
  }

  const obj = value as Record<string, unknown>

  // Check version
  if (obj.version !== '2.0') {
    return false
  }

  // Check project
  if (typeof obj.project !== 'object' || obj.project === null) {
    return false
  }
  const project = obj.project as Record<string, unknown>
  if (typeof project.name !== 'string') {
    return false
  }
  // defaultBaseBranch is optional (non-git projects may not have one), but if present must be a string
  if (project.defaultBaseBranch !== undefined && typeof project.defaultBaseBranch !== 'string') {
    return false
  }

  // Check setup
  if (typeof obj.setup !== 'object' || obj.setup === null) {
    return false
  }
  const setup = obj.setup as Record<string, unknown>
  if (!Array.isArray(setup.filesToCopy) || !Array.isArray(setup.postSetupCommands)) {
    return false
  }

  return true
}
